#!/usr/bin/env python3
"""compute_table_latency_v2.py -- main-text Tables 1 and 2 (tab:pqc_overhead, tab:dmax_results) for the QRQT revision.

Run:  python -I compute_table_latency_v2.py        (from this folder)

Writes, next to this script:
  table_latency_v2.csv   every number of both tables plus the precomputed-KEM comparison variant
  table_latency_v2.tex   the two LaTeX tables (sn-jnl, booktabs):
                           Table 1, label tab:pqc_overhead  -- inputs (benchmark latencies, ciphertext, serialization, T_fixed)
                           Table 2, label tab:dmax_results  -- distance results (hard cutoff and F* = 0.90) and T^B_min(F*)
and, if r1.tex is present, replaces the block between the markers
  % BEGIN table_latency_v2 (generated by compute_table_latency_v2.py -- do not edit by hand)
  % END table_latency_v2
in r1.tex by the same two tables so that the copies cannot drift.

Inputs (REVISION_SPEC_v2 section 3.3; DECISIONS_round3 sections A/B; all public, none measured here):
  * Kyber round-3 specification v3.02 (2021-08-04), Table 2: encaps + decaps cycle counts on one core of an
    Intel Core i7-4770K (Haswell) at 3.49 GHz; AVX2 ("fast") and reference portable C ("portable")
    implementations of the same algorithm.  Kyber512/768/1024 = ML-KEM-512/768/1024 parameter sets.
  * FrodoKEM round-3 specification (2021-06-04): Table 6 ("Total" = Encaps + Decaps, FrodoKEM-AES with AES-NI,
    3.4 GHz Skylake) = "fast"; Table 7 (FrodoKEM-SHAKE, plain C) = "portable".  NOTE: the two FrodoKEM columns
    are two algorithm variants (AES vs SHAKE matrix generation) as well as two implementations.
    "Total" excludes KeyGen (CROSSCHECK item 14, closed 2026-10-20).
  * Ciphertext sizes: FIPS 203 Table 3 (ML-KEM) and FrodoKEM specification Table 5 (unsalted 2021 scheme).
    liboqs 0.16.0 renamed that unsalted scheme eFrodoKEM; the salted FrodoKEM of that release has ciphertexts
    9752 / 15792 / 21696 B (640/976/1344) and must be tabulated separately if ever measured.
  * All cycle counts are normalized to a 3 GHz clock (T = cycles / 3e9), as the original Methods did.
Assumptions (stated as such in the captions):
  * link rate 1 Gb/s, no framing overhead; the AEAD message C2 = 1 B payload + 12 B nonce + 16 B tag = 29 B;
  * AES-128-GCM on one 16-byte block: 0.25 us per side with AES-NI (two sides on the critical path);
  * local operations after storage start (basis change, Bell measurement, Pauli correction) 0.1 us;
    pair preparation precedes the time origin of tau_m (storage start) and is not part of T_fixed;
  * v_fiber = 2e5 km/s = 0.2 km/us; one-way geometry d/v on Bob's memory with an already established shared pair,
    prior storage age tau_0 = 0.
Criteria:
  * hard cutoff (named baseline, main-text Eq. max_distance): d_max = (T_coh^B - T_fixed) v_fiber,
    "infeasible" when T_fixed >= T_coh^B; T^B_min(hard) = T_fixed at d -> 0.
  * fidelity target F* = 0.90 (main-text Eq. dmax_fstar / tbmin): with L = ln(1/(2F*-1)) = ln 1.25,
    d_max(F*) = v_fiber (T_coh^B L - T_fixed), "infeasible" when negative;  T^B_min(F*) = tau_m / L,
    tabulated at d -> 0 (tau_m = T_fixed); each km adds (1/v_fiber)/L = 22.4 us.
Schedules:
  * serial (baseline, one KEM per round after the Bell measurement): T_fixed = T_loc + T_KEM + 2 T_AEAD + T_ser(C1 + C2)
  * precomputed-KEM comparison variant (readiness condition: key material ready at both parties before storage
    starts): T_fixed = T_loc + 2 T_AEAD + T_ser(C2)
  * no-PQC reference (latency lower bound, no equivalent protection): T_fixed = T_loc + T_ser(1 B)
"""
import csv
import math
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))

# ---------------------------------------------------------------- inputs
CLOCK_HZ = 3.0e9           # normalization clock
V_FIBER_KM_PER_US = 0.2    # 2e5 km/s
LINK_RATE_BPS = 1.0e9      # assumption
T_LOC_US = 0.1             # local operations after storage start (Methods, SI Note si:latency)
T_AEAD_US = 0.25           # per side, AES-NI assumption
C2_BYTES = 1 + 12 + 16     # 2-bit payload byte-aligned + nonce + tag
T_COH_B_US = (1000.0, 10000.0)   # 1 ms = main reference value; 10 ms = comparison
F_STAR = 0.90                    # fidelity target of the quality-constrained comparison
LN_FACTOR = math.log(1.0 / (2.0 * F_STAR - 1.0))   # ln(1.25) = 0.223144
US_PER_KM_FSTAR = (1.0 / V_FIBER_KM_PER_US) / LN_FACTOR   # 22.41 us of lifetime per km at F*

# scheme, NIST category, cycles fast (AVX2 / AES-NI), cycles portable (ref C / plain-C SHAKE), ciphertext bytes
SCHEMES = [
    ("Kyber512 (ML-KEM-512)",   1,   79_772,    342_484,   768),
    ("Kyber768 (ML-KEM-768)",   3,  120_780,    510_160,  1088),
    ("Kyber1024 (ML-KEM-1024)", 5,  176_452,    743_232,  1568),
    ("FrodoKEM-640",            1, 3_171_000, 15_590_000,  9720),
    ("FrodoKEM-976",            3, 5_951_000, 34_072_000, 15744),
    ("FrodoKEM-1344",           5, 9_903_000, 61_077_000, 21632),
]

# cross-check 1: microsecond values quoted in the task sheet
EXPECTED_US = {
    "Kyber512 (ML-KEM-512)":   (26.6, 114.2),
    "Kyber768 (ML-KEM-768)":   (40.3, 170.1),
    "Kyber1024 (ML-KEM-1024)": (58.8, 247.7),
    "FrodoKEM-640":            (1057, 5197),
    "FrodoKEM-976":            (1984, 11357),
    "FrodoKEM-1344":           (3301, 20359),
}
# cross-check 2: independent arithmetic of the review (REVIEW_v2 section 4.3): T_fixed fast (us),
# d_max(1 ms) fast / portable (km) under the hard cutoff; Kyber768 at F* = 0.90: 34.6695 / 8.7108 km
REVIEW_CHECK = {
    "Kyber512 (ML-KEM-512)":   (33.5667, 193.2867, 175.7725),
    "Kyber768 (ML-KEM-768)":   (49.7960, 190.0408, 164.0821),
    "Kyber1024 (ML-KEM-1024)": (72.1933, 185.5613, 147.7760),
}
REVIEW_CHECK_FSTAR_KYBER768 = (34.6695, 8.7108)


def us_from_cycles(c):
    return c / CLOCK_HZ * 1e6


def t_ser_us(nbytes):
    return nbytes * 8 / LINK_RATE_BPS * 1e6


def d_max_km(t_coh_us, t_fixed_us):
    """Hard cutoff of Eq. max_distance; None = infeasible (T_fixed >= T_coh^B)."""
    if t_fixed_us >= t_coh_us:
        return None
    return (t_coh_us - t_fixed_us) * V_FIBER_KM_PER_US


def d_max_fstar_km(t_coh_us, t_fixed_us):
    """Fidelity-target form, Eq. dmax_fstar; None = infeasible (bracket negative or zero)."""
    budget = t_coh_us * LN_FACTOR
    if t_fixed_us >= budget:
        return None
    return (budget - t_fixed_us) * V_FIBER_KM_PER_US


def t_bmin_fstar_us(tau_m_us):
    """Lifetime required at F* for a given wait, Eq. tbmin."""
    return tau_m_us / LN_FACTOR


def fmt_km(x, nd=1):
    return "infeasible" if x is None else f"{x:.{nd}f}"


# ---------------------------------------------------------------- compute
rows = []
for name, cat, cyc_fast, cyc_port, ct in SCHEMES:
    t_fast = us_from_cycles(cyc_fast)
    t_port = us_from_cycles(cyc_port)
    exp_fast, exp_port = EXPECTED_US[name]
    assert abs(t_fast - exp_fast) < 0.6, (name, t_fast, exp_fast)
    assert abs(t_port - exp_port) < 0.6, (name, t_port, exp_port)
    tser = t_ser_us(ct + C2_BYTES)
    tfix_fast = T_LOC_US + t_fast + 2 * T_AEAD_US + tser
    tfix_port = T_LOC_US + t_port + 2 * T_AEAD_US + tser
    tfix_pre = T_LOC_US + 2 * T_AEAD_US + t_ser_us(C2_BYTES)
    r = dict(scheme=name, nist_category=cat,
             cycles_fast_avx2_aesni=cyc_fast, cycles_portable_c=cyc_port,
             T_KEM_fast_us=t_fast, T_KEM_portable_us=t_port,
             ciphertext_C1_bytes=ct, C2_bytes=C2_BYTES,
             T_ser_C1C2_1Gbps_us=tser,
             measured_encaps_decaps_us="",          # reserved; stays empty until measured
             T_fixed_serial_fast_us=tfix_fast, T_fixed_serial_portable_us=tfix_port,
             T_fixed_precomputed_us=tfix_pre)
    for tcoh in T_COH_B_US:
        tag = f"{int(tcoh/1000)}ms"
        r[f"d_max_hard_serial_fast_{tag}_km"] = d_max_km(tcoh, tfix_fast)
        r[f"d_max_hard_serial_portable_{tag}_km"] = d_max_km(tcoh, tfix_port)
        r[f"d_max_hard_precomputed_{tag}_km"] = d_max_km(tcoh, tfix_pre)
        r[f"d_max_F090_serial_fast_{tag}_km"] = d_max_fstar_km(tcoh, tfix_fast)
        r[f"d_max_F090_serial_portable_{tag}_km"] = d_max_fstar_km(tcoh, tfix_port)
        r[f"d_max_F090_precomputed_{tag}_km"] = d_max_fstar_km(tcoh, tfix_pre)
    # lifetime requirements at d -> 0 (tau_m = T_fixed)
    r["T_Bmin_hard_serial_fast_us"] = tfix_fast
    r["T_Bmin_hard_serial_portable_us"] = tfix_port
    r["T_Bmin_F090_serial_fast_us"] = t_bmin_fstar_us(tfix_fast)
    r["T_Bmin_F090_serial_portable_us"] = t_bmin_fstar_us(tfix_port)
    r["T_Bmin_F090_precomputed_us"] = t_bmin_fstar_us(tfix_pre)
    # example at d = 100 km (quoted in the text for the representative set)
    r["T_Bmin_F090_serial_fast_100km_us"] = t_bmin_fstar_us(tfix_fast + 100.0 / V_FIBER_KM_PER_US)
    rows.append(r)

# no-PQC reference: the two correction bits sent in one plaintext byte, no KEM, no AEAD
tfix_nopqc = T_LOC_US + t_ser_us(1)
ref = dict(scheme="no PQC (latency lower bound; no equivalent protection)", nist_category="",
           cycles_fast_avx2_aesni="", cycles_portable_c="",
           T_KEM_fast_us=0.0, T_KEM_portable_us=0.0, ciphertext_C1_bytes="", C2_bytes=1,
           T_ser_C1C2_1Gbps_us=t_ser_us(1), measured_encaps_decaps_us="",
           T_fixed_serial_fast_us=tfix_nopqc, T_fixed_serial_portable_us=tfix_nopqc,
           T_fixed_precomputed_us=tfix_nopqc)
for tcoh in T_COH_B_US:
    tag = f"{int(tcoh/1000)}ms"
    for k in ("serial_fast", "serial_portable", "precomputed"):
        ref[f"d_max_hard_{k}_{tag}_km"] = d_max_km(tcoh, tfix_nopqc)
        ref[f"d_max_F090_{k}_{tag}_km"] = d_max_fstar_km(tcoh, tfix_nopqc)
ref["T_Bmin_hard_serial_fast_us"] = tfix_nopqc
ref["T_Bmin_hard_serial_portable_us"] = tfix_nopqc
ref["T_Bmin_F090_serial_fast_us"] = t_bmin_fstar_us(tfix_nopqc)
ref["T_Bmin_F090_serial_portable_us"] = t_bmin_fstar_us(tfix_nopqc)
ref["T_Bmin_F090_precomputed_us"] = t_bmin_fstar_us(tfix_nopqc)
ref["T_Bmin_F090_serial_fast_100km_us"] = t_bmin_fstar_us(tfix_nopqc + 100.0 / V_FIBER_KM_PER_US)
rows.append(ref)

# derived quantities quoted in the text (penalty relative to the no-PQC row; independent of T_coh^B and of F*)
for r in rows[:-1]:
    r["penalty_serial_fast_km"] = (r["T_fixed_serial_fast_us"] - tfix_nopqc) * V_FIBER_KM_PER_US
    r["penalty_serial_portable_km"] = (r["T_fixed_serial_portable_us"] - tfix_nopqc) * V_FIBER_KM_PER_US
    r["penalty_precomputed_km"] = (r["T_fixed_precomputed_us"] - tfix_nopqc) * V_FIBER_KM_PER_US
    r["KEM_rounds_per_core_per_s_fast"] = 1e6 / r["T_KEM_fast_us"]
    r["KEM_rounds_per_core_per_s_portable"] = 1e6 / r["T_KEM_portable_us"]

# cross-check 2 (review's independent arithmetic)
for name, (tf, d1f, d1p) in REVIEW_CHECK.items():
    r = next(x for x in rows if x["scheme"] == name)
    assert abs(r["T_fixed_serial_fast_us"] - tf) < 5e-4, (name, r["T_fixed_serial_fast_us"], tf)
    assert abs(r["d_max_hard_serial_fast_1ms_km"] - d1f) < 5e-4, (name, r["d_max_hard_serial_fast_1ms_km"], d1f)
    assert abs(r["d_max_hard_serial_portable_1ms_km"] - d1p) < 5e-4, (name, r["d_max_hard_serial_portable_1ms_km"], d1p)
k768 = next(x for x in rows if x["scheme"].startswith("Kyber768"))
assert abs(k768["d_max_F090_serial_fast_1ms_km"] - REVIEW_CHECK_FSTAR_KYBER768[0]) < 5e-4, k768["d_max_F090_serial_fast_1ms_km"]
assert abs(k768["d_max_F090_serial_portable_1ms_km"] - REVIEW_CHECK_FSTAR_KYBER768[1]) < 5e-4, k768["d_max_F090_serial_portable_1ms_km"]

# ---------------------------------------------------------------- CSV
fields = list(rows[0].keys())
csv_path = os.path.join(HERE, "table_latency_v2.csv")
with open(csv_path, "w", newline="", encoding="utf-8") as f:
    w = csv.writer(f)
    w.writerow(["# generated by compute_table_latency_v2.py; cycles normalized to 3 GHz; link 1 Gb/s (assumption);"
                " T_AEAD 0.25 us/side (AES-NI assumption); T_loc 0.1 us (after storage start); C2 = 29 B;"
                " v_fiber 0.2 km/us; one-way geometry, shared pair already established, prior storage age 0;"
                " hard cutoff d_max = (T_coh^B - T_fixed) v_fiber; F* = 0.90: d_max = v_fiber (T_coh^B ln(1/(2F*-1)) - T_fixed),"
                " T_Bmin = tau_m / ln(1/(2F*-1)) with tau_m = T_fixed (d -> 0) unless stated; empty km = infeasible;"
                " measured values on the authors' hardware are reported separately in Supplementary Table tab:measured_latency (not merged into this table);"
                " fast = Kyber AVX2 / FrodoKEM-AES AES-NI, portable = Kyber ref C / FrodoKEM-SHAKE plain C"])
    w.writerow(fields)
    for r in rows:
        out = []
        for k in fields:
            v = r.get(k, "")
            if v is None:
                v = ""
            elif isinstance(v, float):
                v = f"{v:.4f}"
            out.append(v)
        w.writerow(out)

# ---------------------------------------------------------------- LaTeX tables
def cell_two(a, b, nd=1):
    """'a / b' cell for the fast and portable latency models."""
    fa, fb = fmt_km(a, nd), fmt_km(b, nd)
    return fa if fa == fb else f"{fa} / {fb}"


def ms(x):
    return f"{x/1000:.2f}"


# Font: the sn-jnl class maps \scriptsize to 9 pt (and \footnotesize to 7 pt); the layout decision forbids any font
# below \scriptsize, so both tables are set at \scriptsize and fitted to the 372 pt text width (and the 553 pt text
# height) by the column split, not by shrinking: Table 1 keeps one row per scheme with paired fast / portable cells,
# Table 2 uses one row per implementation (single-number cells).
FONT = r"\scriptsize"
SHORT_NAME = {   # Table 2 uses the standardized names; the caption maps them to the Kyber benchmarks of Table 1
    "Kyber512 (ML-KEM-512)": "ML-KEM-512",
    "Kyber768 (ML-KEM-768)": "ML-KEM-768",
    "Kyber1024 (ML-KEM-1024)": "ML-KEM-1024",
}

lines = []
# ---- Table 1: inputs
lines.append(r"\begin{table*}[htbp]")
lines.append(
    r"\caption{PQC overhead of the serial schedule: the inputs of the distance results in Table~\ref{tab:dmax_results}. "
    r"$T_{\mathrm{KEM}}$ is one encapsulation plus one decapsulation (key generation amortized over the reusable key) "
    r"from public single-core cycle counts normalized to a $3$~GHz clock, fast and portable denoting the AVX2 and "
    r"portable C implementations of Kyber512/768/1024 (standardized as ML-KEM-512/768/1024~\cite{FIPS203}) and the "
    r"AES-NI and plain-C SHAKE variants of FrodoKEM~\cite{KyberSpec2021,FrodoKEMSpec2021}. $|C_1|$ is the ciphertext "
    r"size of the cited specifications; $T_{\mathrm{ser}}$ serializes $C_1$ plus the $29$-byte AEAD message $C_2$ at an "
    r"assumed $1$~Gb/s; $T_{\text{fixed}}$ is the resulting distance-independent delay (Methods); Cat.\ is the NIST "
    r"security category. The no-PQC row, which sends the two correction bits as one plaintext byte, is a latency "
    r"lower-bound reference that offers no equivalent protection. These are microbenchmarks of the classical primitives, "
    r"not end-to-end teleportation measurements; benchmark sources, variant identities and the values measured on the "
    r"authors' hardware are documented in Supplementary Note~\SIref{si:jedi}.}")
lines.append(r"\label{tab:pqc_overhead}")
lines.append(r"\centering")
lines.append(FONT)
lines.append(r"\setlength{\tabcolsep}{3pt}")
lines.append(r"\begin{tabular}{lccccc}")
lines.append(r"\toprule")
lines.append(r"Scheme & Cat. & $|C_1|$ & $T_{\mathrm{ser}}$ & $T_{\mathrm{KEM}}$ ($\mu$s) & $T_{\text{fixed}}$ ($\mu$s) \\")
lines.append(r" & & (B) & ($\mu$s) & fast / portable & fast / portable \\")
lines.append(r"\midrule")
for r in rows[:-1]:
    lines.append(
        f"{r['scheme']} & {r['nist_category']} & {r['ciphertext_C1_bytes']} & {r['T_ser_C1C2_1Gbps_us']:.2f} & "
        f"{cell_two(r['T_KEM_fast_us'], r['T_KEM_portable_us'])} & "
        f"{cell_two(r['T_fixed_serial_fast_us'], r['T_fixed_serial_portable_us'])} \\\\")
lines.append(r"\midrule")
r = rows[-1]
lines.append(
    f"no PQC (lower-bound ref.) & -- & -- & {r['T_ser_C1C2_1Gbps_us']:.3f} & -- & "
    f"{r['T_fixed_serial_fast_us']:.3f} \\\\")
lines.append(r"\bottomrule")
lines.append(r"\end{tabular}")
lines.append(r"\end{table*}")
lines.append("")
# ---- Table 2: distance results, one row per implementation
lines.append(r"\begin{table*}[htbp]")
lines.append(
    r"\caption{Memory-limited maximum distance under the serial schedule for the inputs of Table~\ref{tab:pqc_overhead}, "
    r"one row per implementation (fast / portable as defined there; the ML-KEM-512/768/1024 rows use the Kyber512/768/1024 benchmarks). "
    r"Hard cutoff, the baseline criterion (Eq.~\eqref{eq:max_distance}): $d_{\max} = (T^{B}_{\mathrm{coh}} - T_{\text{fixed}})\,v_{\mathrm{fiber}}$, "
    r"which corresponds to a fidelity of about $0.68$ at the moment of correction. Target fidelity $F^{*} = 0.90$: $d_{\max}(F^{*})$ of "
    r"Eq.~\eqref{eq:dmax_fstar} with $\ln(1/(2F^{*}-1)) = \ln 1.25 \approx 0.223$; ``infeasible'' marks a negative bracket. "
    r"$T^{B}_{\min}(F^{*}) = T_{\text{fixed}}/\ln 1.25$ (Eq.~\eqref{eq:tbmin} at $\tau_m = T_{\text{fixed}}$) is the lifetime below which "
    r"the scheme is infeasible at $F^{*} = 0.90$ at any distance; each kilometer of fiber adds $22.4~\mu$s to it. "
    r"$T^{B}_{\mathrm{coh}} = 1$~ms is the reference value and $10$~ms the comparison value (model parameters, not performance claims); "
    r"$v_{\mathrm{fiber}} = 2\times10^{5}$~km/s, one-way geometry, shared pair already established, prior storage age zero. "
    r"The no-PQC row is the latency lower-bound reference of Table~\ref{tab:pqc_overhead}. Values computed by "
    r"\texttt{compute\_table\_latency\_v2.py} (\texttt{table\_latency\_v2.csv}).}")
lines.append(r"\label{tab:dmax_results}")
lines.append(r"\centering")
lines.append(FONT)
lines.append(r"\setlength{\tabcolsep}{3pt}")
lines.append(r"\begin{tabular}{llccccc}")
lines.append(r"\toprule")
lines.append(r" & & \multicolumn{2}{c}{$T^{B}_{\mathrm{coh}} = 1$~ms} & "
             r"\multicolumn{2}{c}{$T^{B}_{\mathrm{coh}} = 10$~ms} & $T^{B}_{\min}$ \\")
lines.append(r"\cmidrule(lr){3-4}\cmidrule(lr){5-6}")
lines.append(r"Scheme & Impl. & hard cutoff & $F^{*}=0.90$ & hard cutoff & $F^{*}=0.90$ & $F^{*}=0.90$ \\")
lines.append(r" & & (km) & (km) & (km) & (km) & (ms) \\")
lines.append(r"\midrule")
for r in rows[:-1]:
    for impl in ("fast", "portable"):
        name = SHORT_NAME.get(r["scheme"], r["scheme"]) if impl == "fast" else ""
        lines.append(
            f"{name} & {impl} & "
            f"{fmt_km(r[f'd_max_hard_serial_{impl}_1ms_km'])} & {fmt_km(r[f'd_max_F090_serial_{impl}_1ms_km'])} & "
            f"{fmt_km(r[f'd_max_hard_serial_{impl}_10ms_km'])} & {fmt_km(r[f'd_max_F090_serial_{impl}_10ms_km'])} & "
            f"{ms(r[f'T_Bmin_F090_serial_{impl}_us'])} \\\\")
lines.append(r"\midrule")
r = rows[-1]
lines.append(
    f"no PQC (ref.) & -- & {fmt_km(r['d_max_hard_serial_fast_1ms_km'])} & "
    f"{fmt_km(r['d_max_F090_serial_fast_1ms_km'])} & {fmt_km(r['d_max_hard_serial_fast_10ms_km'])} & "
    f"{fmt_km(r['d_max_F090_serial_fast_10ms_km'])} & {r['T_Bmin_F090_serial_fast_us']/1000:.4f} \\\\")
lines.append(r"\bottomrule")
lines.append(r"\end{tabular}")
lines.append(r"\end{table*}")
table_tex = "\n".join(lines) + "\n"

tex_path = os.path.join(HERE, "table_latency_v2.tex")
with open(tex_path, "w", encoding="utf-8") as f:
    f.write("% table_latency_v2.tex -- generated by compute_table_latency_v2.py; do not edit by hand\n")
    f.write("% Table 1 (tab:pqc_overhead): inputs. Table 2 (tab:dmax_results): distance results.\n")
    f.write(table_tex)

# splice into r1.tex between markers (if present)
BEGIN = "% BEGIN table_latency_v2 (generated by compute_table_latency_v2.py -- do not edit by hand)"
END = "% END table_latency_v2"
r1_path = os.path.join(HERE, "r1.tex")
if os.path.exists(r1_path):
    with open(r1_path, encoding="utf-8") as f:
        src = f.read()
    if BEGIN in src and END in src:
        pat = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
        new = pat.sub(lambda m: BEGIN + "\n" + table_tex + END, src)
        with open(r1_path, "w", encoding="utf-8") as f:
            f.write(new)
        print("r1.tex: table block replaced (Tables 1 and 2)")
    else:
        print("r1.tex: markers not found, tables not spliced")

